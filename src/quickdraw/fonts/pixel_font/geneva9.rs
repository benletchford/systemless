//! Kurrajong 9 — our own humanist body sans at 9px (systemless
//! compatibility face for Geneva 9). Metrics (advance, origin_x,
//! x-height 5 / cap height 7, side-bearings) are conformed to the
//! original Geneva 9 strike so text lays out identically; the pixels are
//! our own hand-drawn letterforms in the Kurrajong house style (flat-arch
//! m/n, slashed 0, footed 1, closed 4, open-tail g). At 5px x-height most
//! plain glyphs converge on the one good humanist solution, but every
//! pixel was authored by us, not lifted from a font binary.

