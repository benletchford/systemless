//! Kurrajong 12 — our own humanist body sans at 12px (systemless
//! compatibility face for Geneva 12 / Application 12 / Helvetica 12).
//! The *metrics* (advance, origin_x, x-height, cap height, side-bearings)
//! are conformed to the original Geneva 12 strike so text lays out
//! identically inside classic apps; the *pixels* are our own hand-drawn
//! letterforms on that grid — a clean humanist construction with
//! deliberate departures from Geneva (our two-story `a`, open-tail `g`,
//! footed `1`, barred `7`, straight-foot `t`, and our own `& @ %`). At
//! 5–7px many plain glyphs necessarily converge on the one good humanist
//! solution, but every pixel here was authored by us, not lifted from a
//! font binary.

