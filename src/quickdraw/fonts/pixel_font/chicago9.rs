//! Jarrah 9 — our own heavy Mac system/UI font at 9px (systemless
//! compatibility face for Chicago 9). Metrics (advance, origin_x,
//! x-height 6 / cap height 7, side-bearings) are conformed to the
//! original Chicago 9 strike so menus/buttons lay out identically; the
//! pixels are our own hand-drawn letterforms — a heavier UI weight than
//! Geneva, with 2px stems where the tight advances allow. Every pixel was
//! authored by us, not lifted from a font binary.

