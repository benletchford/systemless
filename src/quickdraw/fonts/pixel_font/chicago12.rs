//! Jarrah 12 — our own heavy Mac system/UI font at 12px (systemless
//! compatibility face for Chicago 12). Metrics (advance, origin_x,
//! x-height 7 / cap height 9, side-bearings) are conformed to the
//! original Chicago 12 strike so menus, buttons and titles lay out
//! identically; the pixels are our own hand-drawn letterforms — a heavy
//! humanist UI weight with 2px stems, distinct from Geneva's light body
//! face. Every pixel was authored by us, not lifted from a font binary.

