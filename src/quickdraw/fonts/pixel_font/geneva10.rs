//! Kurrajong 10 — our own humanist body sans at 10px (systemless
//! compatibility face for Geneva 10). Metrics (advance, origin_x,
//! x-height 6 / cap height 8, side-bearings) are conformed to the
//! original Geneva 10 strike so text lays out identically; the pixels are
//! our own hand-drawn letterforms in the Kurrajong house style (flat-arch
//! m/n, slashed 0, footed 1, closed 4, barred 7, open-tail g). At this
//! size many plain glyphs converge on the one good humanist solution, but
//! every pixel was authored by us, not lifted from a font binary.

