//! compatibility face for Geneva 14). Metrics (advance, origin_x,
//! x-height 8 / cap height 11, side-bearings) are conformed to the
//! original Geneva 14 strike so text lays out identically; the pixels are
//! our own hand-drawn letterforms in the Kurrajong house style (flat-arch
//! m/n, slashed 0, footed 1, closed 4, barred 7, open-tail g). Every
//! pixel was authored by us, not lifted from a font binary.

