pub(super) fn method_name(index: u32) -> Option<&'static str> {
    let method = index.checked_sub(PPC_AGL_METHOD_IMPORT_BASE)?;
    METHODS.get(method as usize).copied()
}

pub(super) fn publish_context(memory: &mut PpcSectionMem, pointer: u32) -> Option<()> {
    if !ppc_memory_can_write_bytes(memory, pointer, PPC_AGL_CONTEXT_BYTES) {
        return None;
    }
    memory.write_u32_be(pointer, pointer)?;
    for method in 0..PPC_AGL_METHOD_COUNT {
        let offset = if method < CORE_COUNT as u32 {
            4 + method * 4
        } else {
            8 + method * 4 // skip extension count
        };
        let vector = PPC_IMPORT_TVECTOR_BASE + (PPC_AGL_METHOD_IMPORT_BASE + method) * 8;
        memory.write_u32_be(pointer + offset, vector)?;
    }
    memory.write_u32_be(pointer + 4 + CORE_COUNT as u32 * 4, EXTENSION_COUNT as u32)?;
    Some(())
}

pub(super) fn create_context(
    cpu: &PpcCpu,
    memory: &mut PpcSectionMem,
    manager: &mut ProcessNativeMemoryManager,
    agl: &mut PpcAglState,
    heap_cursor: &mut u32,
    last_mem_error: &mut i16,
) -> u32 {
    if agl.pixel_format(cpu.gpr[3]).is_none() {
        agl.set_error(classic_gl_agl::AGL_BAD_PIXELFMT);
        return 0;
    }
    if cpu.gpr[4] != 0 && agl.context(cpu.gpr[4]).is_none() {
        agl.set_error(10009); // AGL_BAD_MATCH, agl.h
        return 0;
    }
    let pointer = manager.new_native_ptr(memory, PPC_AGL_CONTEXT_BYTES, true);
    ppc_apply_process_native_allocator(manager, memory, heap_cursor, last_mem_error);
    if pointer == 0 {
        agl.set_error(10016); // AGL_BAD_ALLOC, agl.h
        return 0;
    }
    if publish_context(memory, pointer).is_none()
        || agl.create_context_at(cpu.gpr[3], cpu.gpr[4], pointer) == 0
    {
        let _ = manager.dispose_native_ptr(pointer);
        ppc_apply_process_native_allocator(manager, memory, heap_cursor, last_mem_error);
        agl.set_error(10016);
        return 0;
    }
    agl.context_mut(pointer).unwrap().guest_record = true;
    pointer
}

pub(super) fn destroy_context(
    pointer: u32,
    memory: &mut PpcSectionMem,
    manager: &mut ProcessNativeMemoryManager,
    agl: &mut PpcAglState,
    heap_cursor: &mut u32,
    last_mem_error: &mut i16,
) -> bool {
    let owned = agl
        .context(pointer)
        .is_some_and(|context| context.guest_record);
    if !agl.destroy_context(pointer) {
        agl.set_error(classic_gl_agl::AGL_BAD_CONTEXT);
        return false;
    }
    if owned {
        let _ = memory.write_bytes(pointer, &vec![0; PPC_AGL_CONTEXT_BYTES as usize]);
        let _ = manager.dispose_native_ptr(pointer);
        ppc_apply_process_native_allocator(manager, memory, heap_cursor, last_mem_error);
    }
    true
}
