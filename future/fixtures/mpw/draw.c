#include <Types.h>
#include <Quickdraw.h>
#include <Resources.h>
#include <Memory.h>
#include <Events.h>
#include <Processes.h>

QDGlobals qd;
static unsigned char pixels[8] = {0x80,0x33,0,0x44,0,0x55,0,0x66};
int main(void) {
    GrafPort port;
    GrafPort other;
    GrafPtr current;
    BitMap bitmap;
    Rect all = {0,0,4,8};
    Rect clip = {1,1,3,7};
    Rect patch = {1,2,2,4};
    Rect hole = {1,2,3,6};
    Rect translated = {-70,-60,-66,-52};
    EventRecord event;
    Point inside, outside;
    Handle data;
    PatHandle pattern;
    Handle resized;
    RgnHandle visible, clipping, saved, temporary;
    InitGraf(&qd.thePort);
    if (qd.thePort != 0 || qd.randSeed != 1) return 1;
    if (Random() != 16807 || qd.randSeed != 16807) return 28;
    if (Random() != 15089 || qd.randSeed != 282475249) return 29;
    if (Random() != -21287 || qd.randSeed != 1622650073) return 30;
    qd.randSeed = 958682087;
    if (Random() != 0 || qd.randSeed != 32768) return 31;
    qd.randSeed = 0;
    if (Random() != 0 || qd.randSeed != 0) return 32;
    qd.randSeed = 1;
    GetPort(&current);
    if (current != 0) return 7;
    OpenPort(&port);
    OpenPort(&other);
    SetPort(&port);
    GetPort(&current);
    if (current != &port) return 2;
    TextFont(-123);
    TextSize(18);
    TextFace(bold | italic);
    TextMode(srcOr);
    if (port.txFont!=-123 || port.txSize!=18 || port.txFace!=(bold|italic) || port.txMode!=srcOr) return 44;
    if (other.txFont || other.txFace || other.txMode!=srcOr) return 45;
    SetPort(&other);
    TextSize(9);
    TextFace(underline);
    if (other.txSize!=9 || other.txFace!=underline || port.txSize!=18) return 46;
    SetPort(&port);
    bitmap.baseAddr = (Ptr)pixels;
    bitmap.rowBytes = 2;
    bitmap.bounds = translated;
    SetPortBits(&bitmap);
    inside.v=3; inside.h=4;
    LocalToGlobal(&inside);
    if (inside.v != 73 || inside.h != 64) return 25;
    GlobalToLocal(&inside);
    if (inside.v != 3 || inside.h != 4) return 26;
    SetPort(&other);
    LocalToGlobal(&inside);
    if (inside.v != 3 || inside.h != 4) return 27;
    SetPort(&port);
    bitmap.bounds = all;
    SetPortBits(&bitmap);
    ClipRect(&clip);
    saved = NewRgn();
    temporary = NewRgn();
    if (!saved || !temporary) return 14;
    if (!EmptyRgn(saved)) return 15;
    GetClip(saved);
    inside.v=1; inside.h=2; outside.v=3; outside.h=7;
    if (!PtInRgn(inside,saved) || PtInRgn(outside,saved) || EmptyRgn(saved)) return 16;
    RectRgn(temporary,&patch);
    SetClip(temporary);
    CopyRgn(saved,temporary);
    SetClip(temporary);
    DisposeRgn(saved);
    DisposeRgn(temporary);
    data = GetResource('DATA',128);
    if (!data || GetHandleSize(data) != 3 || **data != 1) return 3;
    pattern = GetPattern(-123);
    if (!pattern || (Handle)pattern != GetResource('PAT ',-123)) return 38;
    if (GetHandleSize((Handle)pattern)!=8 || ((unsigned char *)*pattern)[0]!=0xaa) return 39;
    if (GetPattern(-124)!=0 || ResError()!=-192) return 40;
    PenPat(*pattern);
    PaintRect(&all);
    ReleaseResource((Handle)pattern);
    PenPat(&qd.black);
    PenMode(patXor);
    PaintRect(&patch);
    pixels[2] ^= 2;
    PaintRect(&patch);
    if (pixels[0] != 0x80 || pixels[2] != 0x56 || pixels[4] != 0x2a || pixels[6] != 0) return 4;
    if (pixels[1] != 0x33 || pixels[3] != 0x44 || pixels[5] != 0x55 || pixels[7] != 0x66) return 5;
    PostEvent(keyDown,42);
    if (!WaitNextEvent(keyDownMask,&event,0,0) || event.message != 42) return 6;
    temporary = NewRgn();
    saved = NewRgn();
    RectRgn(saved,&all);
    RectRgn(temporary,&hole);
    DiffRgn(saved,temporary,temporary);
    SectRgn(saved,temporary,temporary);
    XorRgn(saved,temporary,saved);
    if (!PtInRgn(inside,saved)) return 20;
    UnionRgn(saved,temporary,saved);
    XorRgn(saved,saved,saved);
    if (!EmptyRgn(saved)) return 21;
    if (MemError()) return 17;
    DisposeRgn(saved);
    SetClip(temporary);
    PaintRect(&all);
    if (pixels[0]!=0x7f || pixels[2]!=0x95 || pixels[4]!=0xe9 || pixels[6]!=0xff) return 18;
    PaintRect(&all);
    if (pixels[0]!=0x80 || pixels[2]!=0x56 || pixels[4]!=0x2a || pixels[6]!=0) return 19;
    DisposeRgn(temporary);
    RectRgn(port.clipRgn,&clip);
    resized = NewHandle(3);
    if (!resized) return 11;
    (*resized)[0] = 17; (*resized)[1] = 34; (*resized)[2] = 51;
    SetHandleSize(resized,64);
    if (MemError() || GetHandleSize(resized) != 64 || (*resized)[2] != 51) return 12;
    SetHandleSize(resized,1);
    if (MemError() || GetHandleSize(resized) != 1 || **resized != 17) return 13;
    DisposeHandle(resized);
    ClipRect(&all);
    pixels[0]=0; pixels[2]=0; pixels[4]=0; pixels[6]=0;
    PenMode(patCopy);
    FrameRoundRect(&all,4,4);
    if (pixels[0]!=0x7e || pixels[2]!=0x81 || pixels[4]!=0x81 || pixels[6]!=0x7e) return 33;
    PenMode(patXor);
    FrameRoundRect(&all,4,4);
    if (pixels[0] || pixels[2] || pixels[4] || pixels[6]) return 34;
    PaintRoundRect(&all,4,4);
    if (pixels[0]!=0x7e || pixels[2]!=0xff || pixels[4]!=0xff || pixels[6]!=0x7e) return 35;
    port.pnSize.h=2;
    FrameRoundRect(&all,4,4);
    if (pixels[0] || pixels[2]!=0x3c || pixels[4]!=0x3c || pixels[6]) return 36;
    if (pixels[1]!=0x33 || pixels[3]!=0x44 || pixels[5]!=0x55 || pixels[7]!=0x66) return 37;
    port.pnSize.h=1;
    ForeColor(whiteColor);
    BackColor(blackColor);
    if (port.fgColor!=whiteColor || port.bkColor!=blackColor) return 41;
    if (other.fgColor!=blackColor || other.bkColor!=whiteColor) return 42;
    PenMode(patCopy);
    PenPat(&qd.gray);
    PaintRect(&all);
    if (pixels[0]!=0x55 || pixels[2]!=0xaa || pixels[4]!=0x55 || pixels[6]!=0xaa) return 43;
    ForeColor(blackColor);
    BackColor(whiteColor);
    visible = port.visRgn;
    clipping = port.clipRgn;
    SetPort(&other);
    InitPort(&port);
    GetPort(&current);
    if (current != &port || port.visRgn != visible || port.clipRgn != clipping) return 9;
    if (port.pnMode != patCopy || port.portBits.baseAddr != qd.screenBits.baseAddr) return 10;
    ClosePort(&other);
    GetPort(&current);
    if (current != &port) return 8;
    OpenPort(&other);
    SetPort(&other);
    ClosePort(&port);
    ClosePort(&other);
    PostEvent(diskEvt,0x600D);
    ExitToShell();
    return 0;
}
